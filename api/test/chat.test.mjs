// Testes do reconhecimento de nomes/UFs do assistente (índices reais do painel, cópia em test/fixtures).
import { readFileSync } from 'node:fs';
import { detectCandidates, detectUfs } from '../src/chat/nomes.js';
const ix = u => JSON.parse(readFileSync(new URL(`./fixtures/index-${u}.json`, import.meta.url)));
const AL = ix('al'), SP = ix('sp'), DF = ix('df'), SE = ix('se');
let f = 0, n = 0;
const check = (nome, c, info) => { n++; if (!c) f++; console.log(`${c ? '✔' : '✘'} ${nome}${c ? '' : ' → ' + JSON.stringify(info)}`); };
const nomes = (q, i, ig) => detectCandidates(q, i, ig).map(c => `${c.cargo}:${c.n}`);
let r;
r = nomes('Quantos votos JHC teve em Maceió?', AL, ['MACEIÓ']); check('JHC (nome de urna de 3 letras) → governador 45 em AL', r[0] === '3:45' && r.length === 1, r);
r = nomes('e o jhc?', AL); check('jhc minúsculo → 3:45', r[0] === '3:45', r);
r = nomes('Renan Filho', AL); check('Renan Filho → só o governador 15 (sem homônimos)', r.join() === '3:15', r);
r = nomes('Arthur Lira teve quantos votos?', AL); check('Arthur Lira → senado 111', r[0] === '5:111', r);
r = nomes('Quem é ele e que voto teve?', AL); check('frase comum → nenhum candidato', r.length === 0, r);
r = nomes('Quais os 10 mais votados em 2026?', AL); check('"10 mais votados em 2026" não vira número de candidato', r.length === 0, r);
r = nomes('Quem é o candidato número 45?', AL); check('"número 45" → JHC', r[0] === '3:45', r);
r = nomes('Tarcísio ou Haddad em Campinas?', SP, ['CAMPINAS']); check('Tarcísio (acento) e Haddad (parcial) em SP', r.includes('3:10') && r.includes('3:13') && !r.some(x => x.startsWith('7:') && x !== '7:'), r);
r = nomes('Flávio Bolsonaro', SP); check('Flávio Bolsonaro → presidente 22', r[0] === '1:22', r);
r = nomes('Celina Leão ou Leandro Grass?', DF); check('DF: Celina Leão e Leandro Grass', r.includes('3:11') && r.includes('3:13'), r);
r = nomes('E o Valmir?', SE); check('SE: "Valmir" → governador primeiro (desempate por votos)', r[0] === '3:10', r);
r = nomes('Como foi o Fábio em Aracaju?', SE, ['ARACAJU']); check('SE: "Fábio" → governador 55', r[0] === '3:55', r);
check('UF: "Quem venceu em SP?" → sp', detectUfs('Quem venceu em SP?').join() === 'sp');
check('UF: "governador de sp" → sp', detectUfs('governador de sp').join() === 'sp');
check('UF: RS e Pará', detectUfs('e no Rio Grande do Sul e no Pará?').join() === 'rs,pa', detectUfs('e no Rio Grande do Sul e no Pará?'));
check('UF: "se o JHC ganhou" não vira SE', detectUfs('se o JHC ganhou').length === 0);
check('UF: "vou para casa" não vira PA', detectUfs('vou para casa').length === 0);
check('UF: Paraná → pr', detectUfs('Paraná').join() === 'pr');
check('UF: município homônimo ignorado', detectUfs('São Paulo do Potengi', ['SAO PAULO DO POTENGI']).length === 0, detectUfs('São Paulo do Potengi', ['SAO PAULO DO POTENGI']));
console.log(`\n${n - f}/${n} ok`); process.exit(f ? 1 : 0);
